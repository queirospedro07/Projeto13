function normalizarCampos(valor) {
  if (Array.isArray(valor)) return valor.map(normalizarCampos);
  if (!valor || typeof valor !== 'object') return valor;

  return Object.fromEntries(
    Object.entries(valor)
      .filter(
        ([chave]) => !CAMPOS_ANTERIORES[chave] || !Object.hasOwn(valor, CAMPOS_ANTERIORES[chave]),
      )
      .map(([chave, conteudo]) => [CAMPOS_ANTERIORES[chave] || chave, normalizarCampos(conteudo)]),
  );
}

function lerJsonCompativel(texto, revisor) {
  return normalizarCampos(JSON.parse(texto, revisor));
}

